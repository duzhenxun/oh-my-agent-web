#!/bin/sh
# 容器入口：把「远程访问必须先有密码」这条硬规则挡在启动之前。
#
# 为什么要在容器里特别处理：本机安装时，工作台只听 127.0.0.1，你可以在本机页面上
# 「设置 → 远程」里设第一个密码。容器里没有这个「本机页面」—— 容器自己的 127.0.0.1
# 就是容器内部，而 -H 0.0.0.0 之后第一个远程访问只会看到「请设置访问密码」页，
# 而远程**不能**设第一个密码。结果就是：镜像起来了、端口也通了、密码永远设不上。
# 所以这里直接要一个密码，缺了就带着原因退出，而不是让用户对着一个 403 页面猜。
set -eu

DATA_DIR="${AGENT_WEB_DATA_DIR:-/data}"

if [ -z "${AGENT_WEB_PASSWORD:-}" ] && [ ! -s "${DATA_DIR}/password" ]; then
	echo "oh-my-agent-web: 需要设置访问密码。" >&2
	echo "  容器里的 127.0.0.1 只对容器自己有效：你在宿主机浏览器打开时，它算「远程访问」，" >&2
	echo "  而远程**不能设第一个密码**。所以镜像必须先拿到一个密码：" >&2
	echo "    docker run -e AGENT_WEB_PASSWORD='换成你自己的' ..." >&2
	echo "  （第一次想看看界面：也可以把宿主机已有的 ~/.oh-my-agent-web 挂到 /data，密码会跟着过来）" >&2
	exit 1
fi

# --no-open：容器里没有浏览器可开（照旧会打印访问地址）
exec "$@" --no-open
