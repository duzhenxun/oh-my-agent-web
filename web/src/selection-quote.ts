/**
 * 在对话里选中一段文字之后的两个动作（纯函数）：
 *
 *   - 「添加到会话」：正文里留一个编号，输入框里那颗「N 条注释」多一条（评论在那边写）；
 *     想把引文真的写进草稿时走列表里的「放进输入框」—— 下面这个引用块就是它拼的；
 *   - 「在临时聊天中提问」：把同一段引用塞进右侧那条**临时聊天**的输入框。
 *
 * 为什么不把原文直接塞成一句话：模型拿到 `>` 引用块就知道「这是你引我的话」，
 * 而不是「用户自己打的字」。跟文件预览那条 `@path:10-20` 一个思路：给引用，不复制内容。
 */

/**
 * 选中文字 → markdown 引用块。
 *
 * 多行选中要**逐行**加 `>`（只在开头加一次的话，第二行起就变回普通段落了，
 * 模型看不出那也是引用）；选中的空行写成单个 `>`（`> ` 会被某些渲染器吃掉成空段）。
 */
export function quoteOf(text: string): string {
	return text
		.replace(/\r\n/g, "\n")
		.split("\n")
		.map((line) => (line.trim() === "" ? ">" : `> ${line}`))
		.join("\n");
}

/**
 * 把一段引用**接进已有草稿**后面（不清空用户已经打的字）。
 *
 * 前后各空一行：粘在上一句屁股上会被当成那一句的延续，
 * 后面不留空行则用户下一句话会紧贴引用块，看着像引用的一部分。
 */
export function appendQuote(draft: string, quote: string): string {
	const body = draft.replace(/\s+$/, "");
	return body === "" ? `${quote}\n\n` : `${body}\n\n${quote}\n\n`;
}
