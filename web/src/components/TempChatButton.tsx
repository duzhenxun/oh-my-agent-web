import { useT } from "../use-language.ts";

/**
 * 「临时会话」那颗入口 —— 在**顶栏那一排**的最左边第一个（见 SidebarMenu 的 `leadingAction`）。
 * 位置是**固定的行首**，不参与面板排序：面板顺序怎么换，它都待在第一个（用户要求）。
 *
 * 一句话说清它是什么：**在右侧分栏里新开一条临时聊天**（＝侧栏落地页那张「临时聊天」卡、
 * 也是选中文字后「在临时聊天中提问」开的那条：`kind: "side"` 的标签、独立通道、
 * pi 的内存会话、不落盘）。它跟「新会话」是**两个不同的动作**：
 *  - 「新会话」= 换掉主对话（左边那一条，会落盘、会出现在下面的项目列表里）；
 *  - 「临时会话」= 右边再开一条，主对话一个字都不动，关掉就没了。
 * 图标用**会话气泡 💬**（跟右边那条「临时会话」标签同一枚，见 PreviewPanel 的 tabMeta）：
 * 一眼就是「又开一个聊天窗口」，比早先那枚 🎭 更好认 —— 后者像「戏剧 / 演出」，
 * 跟会话没关系（临时会话提示条 / 下拉框里那一项现在也用这枚 💬，全站一个图标）。
 *
 * 图标跟「新会话」同一枚，所以**靠描边区分**:这颗是**虚线**（用户 2026-10-29 定的,
 * 提的「用虚线标怎么样」）—— 虚线在这套界面里就是「草稿 / 不落盘」的语感，
 * 一眼就知道它开出来的是关掉就没的；实心主色那颗才是正式会话。具体样式在
 * `styles/app-bar.css` 的 `.tempchat-btn`（带两个坑的注释）。
 *
 * 位置换过好几次，理由记在这儿：
 *  1. 早先在顶栏紧挨「新会话」，写成虚线胶囊「临时对话」；后来用户要求去掉，
 *     能力本身留着（服务端 `--no-session`、提示条、「保存为正式对话」都还在），
 *     入口只剩右侧落地页那张卡 —— 想用的话得先开分栏、再找卡片，太绕；
 *  2. 放回「会话」这一伙中间（侧栏抬头、「新会话」右边一颗描边胶囊）：挨着「新会话」
 *     才看得出它是「另一种开法」，但侧栏一收起（或手机上抽屉关着）这颗就跟着没了 ——
 *     而它开的恰恰是**右边那块**，跟侧栏开没开没有关系；
 *  3. 后来（用户要求）：挪到**顶栏**、紧挨「技能」图标左边，长成和旁边那排入口
 *     **同一个模子**（`side-foot-btn`：图标 18px、圆角 7px、悬停浅底、无描边）。
 *     它在顶栏里跟「开哪个面板」那排并排，读起来就是「再开一条会话」这个动作；
 *     也顺手解决了第 2 条 —— 顶栏一直在，不管侧栏展开还是收起都摸得到。
 *  4. 再后来（用户要求）：从「技能左边」改成**整排的第一个** —— 面板顺序可自定义之后，
 *     「技能左边」意味着它会被带着到处跑；挂在行首才叫「一直在最左边」。
 *
 * 动作由外面注入（`onClick`）：开标签、展开分栏、切到新标签是 App 的事
 * （`openTool("side")`），这颗只管「长什么样、在哪儿」。
 */
export function TempChatButton({
	onClick,
	showIcon = true,
	showLabel = true,
}: {
	onClick: () => void;
	/** 顶栏的「显示图标 / 显示文案」两个开关（设置 → 界面 → 顶栏文字与图标）由 SidebarMenu 传进来 */
	showIcon?: boolean;
	showLabel?: boolean;
}) {
	const t = useT();
	return (
		<button
			type="button"
			/* 复用那一排入口的类：尺寸 / 悬停 / 窄屏收档全跟着 `.appbar-menu .side-foot-btn` 走
			   （否则它比旁边的技能 / 设置大一圈，看着像另一套控件）。
			   `tempchat-btn` 只做标记，给样式留个抓手。 */
			className="side-foot-btn tempchat-btn"
			onClick={onClick}
			title={t(
				"临时会话：在右侧新开一条聊天（不落盘，关掉就没了）",
				"Temp session: start a separate chat on the right (not saved, gone on close)",
			)}
		>
			{showIcon ? (
				<span className="side-foot-icon" aria-hidden="true">
					💬
				</span>
			) : null}
			{showLabel ? <span className="side-foot-label">{t("临时会话", "Temp session")}</span> : null}
		</button>
	);
}
